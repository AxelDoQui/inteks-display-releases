/**
 * Script para generar iconos simples si no existen
 * Ejecutar: node assets/generate-icons.js
 *
 * NOTA: Para producción, reemplaza icon.ico y tray.png con archivos reales
 * de 256x256 y 32x32 respectivamente.
 */

const fs = require('fs');
const path = require('path');

// Mínimo PNG válido: 1x1 pixel verde
// Header PNG + IHDR + IDAT + IEND
const minimalPNG = Buffer.from([
  0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, // PNG signature
  0x00, 0x00, 0x00, 0x0d,                         // IHDR chunk size
  0x49, 0x48, 0x44, 0x52,                         // IHDR
  0x00, 0x00, 0x00, 0x01,                         // width: 1
  0x00, 0x00, 0x00, 0x01,                         // height: 1
  0x08, 0x02, 0x00, 0x00, 0x00,                   // 8-bit RGB
  0x90, 0x77, 0x53, 0xde,                         // CRC
  0x00, 0x00, 0x00, 0x0c,                         // IDAT chunk size
  0x49, 0x44, 0x41, 0x54,                         // IDAT
  0x08, 0x99, 0x01, 0x01, 0x00, 0x00, 0xfe, 0xff,
  0x00, 0x00, 0x00, 0x02, 0x00, 0x01,
  0x49, 0xb4, 0xe8, 0xb7,                         // CRC
  0x00, 0x00, 0x00, 0x00,                         // IEND chunk size
  0x49, 0x45, 0x4e, 0x44,                         // IEND
  0xae, 0x42, 0x60, 0x82                          // CRC
]);

// ICO mínimo: imagen 1x1
const minimalICO = Buffer.from([
  0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x01, 0x01,
  0x00, 0x00, 0x01, 0x00, 0x18, 0x00, 0x30, 0x00,
  0x00, 0x00, 0x16, 0x00, 0x00, 0x00, 0x28, 0x00,
  0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x02, 0x00,
  0x00, 0x00, 0x18, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0xc8, 0xf0, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00
]);

const assetDir = __dirname;

// Generar icon.ico
const iconPath = path.join(assetDir, 'icon.ico');
if (!fs.existsSync(iconPath)) {
  fs.writeFileSync(iconPath, minimalICO);
  console.log('✓ Generado: icon.ico (placeholder)');
} else {
  console.log('⊘ Existe: icon.ico');
}

// Generar tray.png
const trayPath = path.join(assetDir, 'tray.png');
if (!fs.existsSync(trayPath)) {
  fs.writeFileSync(trayPath, minimalPNG);
  console.log('✓ Generado: tray.png (placeholder)');
} else {
  console.log('⊘ Existe: tray.png');
}

console.log('\n⚠️  Para producción, reemplaza estos archivos con iconos reales:');
console.log('   - icon.ico: 256x256 o superior');
console.log('   - tray.png: 32x32');
